# Renders a bold 8x10 bitmap font for the hires tracker screen -> src/font.inc
from PIL import Image, ImageDraw, ImageFont
import sys
W,H=8,10
f=ImageFont.truetype(sys.argv[1], int(sys.argv[2]))
glyphs=[]
for c in range(32,128):
    im=Image.new('L',(W*4,H*4),0); d=ImageDraw.Draw(im)
    ch=chr(c) if c<127 else ' '
    d.text((W*4//2,H*4//2+int(sys.argv[3])),ch,font=f,fill=255,anchor='mm')
    # center region W x H
    ox,oy=W*4//2-W//2,H*4//2-H//2
    rows=[]
    for y in range(H):
        b=0
        for x in range(W):
            v=im.getpixel((ox+x,oy+y))
            if v>int(sys.argv[4]): b|=0x80>>x
        rows.append(b)
    glyphs.append(rows)
# clearer minus / underscore
glyphs[ord('-')-32]=[0,0,0,0,0x7E,0x7E,0,0,0,0]
glyphs[ord('_')-32]=[0,0,0,0,0,0,0,0,0xFF,0xFF]
# 127 = solid block
glyphs[127-32]=[0xFF]*H
out=open('src/font.inc','w')
out.write('/* generated by tools/mkfont.py: 8x10 bold font, ASCII 32..127 */\nstatic const u8 font8x10[96*10] = {\n')
for i,g in enumerate(glyphs):
    out.write('  '+','.join('0x%02x'%b for b in g)+', /* %r */\n'%chr(i+32))
out.write('};\n')
# preview
pv=Image.new('L',(16*(W+2)*3,6*(H+2)*3),255)
for i,g in enumerate(glyphs):
    cx,cy=(i%16)*(W+2),(i//16)*(H+2)
    for y in range(H):
        for x in range(W):
            if g[y]&(0x80>>x):
                for dx in range(3):
                    for dy in range(3): pv.putpixel(((cx+x)*3+dx,(cy+y)*3+dy),0)
pv.save(sys.argv[5])
