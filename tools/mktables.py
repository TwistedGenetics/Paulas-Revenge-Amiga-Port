import math
o=open('src/tables.inc','w')
o.write('/* generated by tools/mktables.py; included by player.c */\n')
o.write('/* 2^(k/768) in 16.16, k = 0..767 (1/64 semitone steps) */\nstatic const u32 pitch_tab[768] = {\n')
v=[round(65536*2**(k/768)) for k in range(768)]
for i in range(0,768,8): o.write('  '+','.join(str(x) for x in v[i:i+8])+',\n')
o.write('};\n/* vibrato sine, 32 steps, -127..127 */\nstatic const s8 vib_tab[32] = {')
o.write(','.join(str(round(127*math.sin(2*math.pi*i/32))) for i in range(32)))
o.write('};\n')
